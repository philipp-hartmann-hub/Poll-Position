export function parliamentIdFromPath(pathname: string): string | null {
  const m = pathname.match(/^\/parlament\/([^/]+)/);
  return m?.[1] ?? null;
}

export function displayNameForParliament(
  id: string,
  list: Parliament[] = DE_PARLIAMENTS,
): string {
  return list.find((p) => p.id === id)?.name ?? id;
}
